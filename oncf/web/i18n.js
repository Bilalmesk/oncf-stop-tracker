function translateStatic(lang) {
  const table = STATIC[lang] || {};
  const skip = (node) => {
    const parent = node.parentElement;
    if (!parent) return true;
    if (["SCRIPT", "STYLE"].includes(parent.tagName)) return true;
    if (parent.closest("[data-i18n], [data-i18n-html]")) return true;
    return false;
  };
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (skip(node)) continue;
    const raw = node.nodeValue;
    if (node.__i18nOriginal !== undefined && raw !== node.__i18nOriginal && raw !== node.__i18nValue) {
      delete node.__i18nOriginal;
      delete node.__i18nValue;
      continue;
    }
    const original = node.__i18nOriginal !== undefined ? node.__i18nOriginal : raw;
    const key = original.trim();
    if (!key || (!(key in STATIC.fr) && !(key in STATIC.ar))) continue;
    if (node.__i18nOriginal === undefined) node.__i18nOriginal = raw;
    const value = lang === "en" ? null : table[key];
    const next = value ? original.replace(key, value) : original;
    node.nodeValue = next;
    node.__i18nValue = next;
  }
  for (const el of document.querySelectorAll("[title], [aria-label], [placeholder]")) {
    for (const attr of ["title", "aria-label", "placeholder"]) {
      if (!el.hasAttribute(attr)) continue;
      const raw = el.getAttribute(attr);
      const store = `i18nOrig${attr.replace("-", "")}`;
      const lastStore = `${store}Last`;
      const original = el.dataset[store] !== undefined ? el.dataset[store] : raw;
      if (el.dataset[store] !== undefined && raw !== original && raw !== el.dataset[lastStore]) {
        delete el.dataset[store];
        delete el.dataset[lastStore];
        continue;
      }
      const key = (original || "").trim();
      if (!key || (!(key in STATIC.fr) && !(key in STATIC.ar))) continue;
      if (el.dataset[store] === undefined) el.dataset[store] = raw;
      const value = lang === "en" ? null : table[key];
      const next = value || original;
      el.setAttribute(attr, next);
      el.dataset[lastStore] = next;
    }
  }
}


function t(key, vars = {}) {
  const lang = localStorage.getItem("oncf:lang") || "en";
  const table = I18N[lang] || I18N.en;
  let text = table[key] ?? I18N.en[key] ?? key;
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

function currentLang() {
  const saved = localStorage.getItem("oncf:lang") || "en";
  return I18N[saved] ? saved : "en";
}

function applyLanguage(lang) {
  const chosen = I18N[lang] ? lang : "en";
  localStorage.setItem("oncf:lang", chosen);
  document.documentElement.lang = chosen;
  document.documentElement.dir = chosen === "ar" ? "rtl" : "ltr";
  for (const el of document.querySelectorAll("[data-i18n]")) {
    el.textContent = t(el.dataset.i18n);
  }
  for (const el of document.querySelectorAll("[data-i18n-html]")) {
    el.innerHTML = t(el.dataset.i18nHtml);
  }
  for (const el of document.querySelectorAll("[data-i18n-placeholder]")) {
    el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder));
  }
  for (const el of document.querySelectorAll("[data-i18n-title]")) {
    el.setAttribute("title", t(el.dataset.i18nTitle));
  }
  for (const el of document.querySelectorAll("[data-i18n-aria-label]")) {
    el.setAttribute("aria-label", t(el.dataset.i18nAriaLabel));
  }
  if (typeof updateOnboardUi === "function") updateOnboardUi();
  if (typeof renderTripStatus === "function" && typeof state !== "undefined" && state.tripStatus) {
    renderTripStatus(state.tripStatus);
  }
  if (typeof renderReports === "function" && typeof state !== "undefined" && state.reports) {
    renderReports(state.reports);
  }
  if (typeof renderDestinations === "function" && typeof state !== "undefined" && state.destinations) {
    renderDestinations(state.destinations);
  }
  translateStatic(chosen);
  document.title = chosen === "en"
    ? "ONCF Live Map"
    : (STATIC[chosen]?.["ONCF Live Map"] || "ONCF Live Map");
  if (typeof loadPunctuality === "function") loadPunctuality();
}
